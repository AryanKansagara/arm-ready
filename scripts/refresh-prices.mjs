// Regenerates src/engine/ec2Prices.ts from the public AWS price file (us-east-1, Linux, on-demand).
// Usage: node scripts/refresh-prices.mjs
import { writeFileSync } from 'node:fs'
import { REGIONS, slim, sourceUrl } from '../api/prices.js'

const name = REGIONS['us-east-1']
const { asOf, prices } = slim(await (await fetch(sourceUrl(name))).json(), name)
const keys = Object.keys(prices).sort()
if (keys.length < 500) throw new Error('Price file looks incomplete: ' + keys.length)
writeFileSync(new URL('../src/engine/ec2Prices.ts', import.meta.url), `// Generated by scripts/refresh-prices.mjs. Do not edit by hand.
// Source: AWS EC2 On-Demand pricing, ${name}, Linux, USD per hour. Published ${asOf}.
// https://aws.amazon.com/ec2/pricing/on-demand/
export const EC2_PRICES_AS_OF = '${asOf}'
export const EC2_PRICES: Record<string, number> = {
${keys.map(k => `'${k}':${prices[k]}`).join(',').replace(/(.{1,150})(,|$)/g, '$1$2\n')}}
`)
console.log(`${keys.length} instance types, published ${asOf}`)
