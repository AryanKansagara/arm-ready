import { useEffect } from 'react'
import { worklist } from './engine/actions.ts'
import { repoScore, scoreServices } from './engine/classify.ts'
import { costLine, costSummary, DEFAULT_PRICES, PRICES_AS_OF } from './engine/cost.ts'
import { useProject } from './projectData.ts'
import { fmtUsd, Link, NotFound } from './ui.tsx'
import { STATE_LABEL, StatusChip } from './widgets.tsx'

export default function Report({ id }: { id: string }) {
  const { loading, project: p } = useProject(id)
  useEffect(() => { if (p) document.title = `arm64 readiness report: ${p.name}` }, [p?.name])
  if (loading) return <div className="boot"><span className="spinner" /></div>
  if (!p) return <NotFound />
  const findings = p.findings ?? []
  const scores = scoreServices(p.services.map(s => s.name), findings).sort((a, b) => a.score - b.score)
  const work = worklist(findings)
  const lines = p.inventory.map(r => costLine(r, p.prices ?? DEFAULT_PRICES, p.cost.gen, p.cost.perf))
  const cost = lines.length ? costSummary(lines) : null
  const snaps = [...p.snapshots].sort((a, b) => a.createdAt - b.createdAt)
  return (
    <div className="report-page" data-theme-mode="light">
      <div className="report-bar"><Link href={`/app/p/${id}`}>← Back to {p.name}</Link><button type="button" className="btn primary sm" onClick={() => print()}>Print or save as PDF</button></div>
      <article className="report">
        <p className="eyebrow">arm64 migration readiness</p>
        <h1>{p.name}</h1>
        <p className="muted">{p.sampleId ? 'Synthetic sample repo. ' : ''}Scanned {p.scannedAt ? new Date(p.scannedAt).toLocaleString() : 'never'} · {p.files.length} files · {p.services.length} services · generated by Arm Ready</p>
        {!p.findings ? <p>No scan yet. Run a scan first.</p> : <>
          <div className="report-kpis">
            <div><span className="small muted">Readiness</span><b>{repoScore(scores)}</b></div>
            <div><span className="small muted">Blockers</span><b>{findings.filter(f => f.status === 'block').length}</b></div>
            <div><span className="small muted">Warnings</span><b>{findings.filter(f => f.status === 'warn').length}</b></div>
            <div><span className="small muted">Monthly change</span><b>{cost ? `${cost.delta <= 0 ? '−' : '+'}${fmtUsd(Math.abs(cost.delta))}` : '–'}</b></div>
          </div>

          <h2>Services</h2>
          <table className="vt compact"><thead><tr><th>Service</th><th>State</th><th className="num">Score</th><th className="num">Blockers</th><th className="num">Warnings</th><th className="num">Unverified</th><th className="num">Passing</th></tr></thead>
            <tbody>{scores.map(s => <tr key={s.name}><th scope="row">{s.name}</th><td>{STATE_LABEL[s.state]}</td><td className="num">{s.score}</td><td className="num">{s.blockers}</td><td className="num">{s.warnings}</td><td className="num">{s.unknown}</td><td className="num">{s.ok}</td></tr>)}</tbody></table>

          <h2>Worklist ({work.length})</h2>
          <table className="vt compact"><thead><tr><th>Severity</th><th>Where</th><th>Issue and fix</th><th>Status</th></tr></thead>
            <tbody>{work.map(f => <tr key={f.id}><td><StatusChip s={f.status} /></td><td><b>{f.service}</b><div className="where">{f.name}<br />{f.file}:{f.line}</div></td><td><b>{f.title}</b><div className="small">{f.detail}</div>{f.fix && <div className="small"><b>Fix:</b> {f.fix}</div>}</td><td className="small">{p.work[f.id] ?? 'open'}</td></tr>)}</tbody></table>

          {cost && <>
            <h2>Cost estimate</h2>
            <p className="small muted">AWS us-east-1 Linux on-demand prices curated {PRICES_AS_OF}{p.prices ? ' (edited)' : ''}; {p.cost.gen === 'g4' ? 'Graviton4' : 'Graviton3'} targets; default performance factor {p.cost.perf.toFixed(2)}×. Validate with a load test.</p>
            <table className="vt compact"><thead><tr><th>Node group</th><th>x86</th><th>Arm</th><th className="num">Today</th><th className="num">On Arm</th><th className="num">Break-even</th></tr></thead>
              <tbody>{lines.map((l, i) => <tr key={i}><th scope="row">{l.service}</th><td>{l.count}× {l.instance}</td><td>{l.armCount}× {l.target ?? '–'}</td><td className="num">{fmtUsd(l.current)}</td><td className="num">{fmtUsd(l.projected)}</td><td className="num">{l.breakEven ? l.breakEven.toFixed(2) + '×' : '–'}</td></tr>)}
                <tr><th scope="row">Total</th><td /><td /><td className="num"><b>{fmtUsd(cost.current)}</b></td><td className="num"><b>{fmtUsd(cost.projected)}</b></td><td /></tr></tbody></table>
          </>}

          {snaps.length > 1 && <>
            <h2>History</h2>
            <table className="vt compact"><thead><tr><th>Scan</th><th>Date</th><th className="num">Readiness</th></tr></thead>
              <tbody>{snaps.map(s => <tr key={s.id}><td>{s.label}</td><td>{new Date(s.createdAt).toLocaleDateString()}</td><td className="num">{s.score}</td></tr>)}</tbody></table>
          </>}
          <p className="small muted" style={{ marginTop: '2rem' }}>Image platforms come from registry manifest lists, Python verdicts from PyPI wheel tags, npm verdicts from registry metadata, and Go/Java/Rust notes from a curated list. Scores: 100 minus 25 per blocker (max 75), 6 per warning (max 30), 4 per unverified item (max 15).</p>
        </>}
      </article>
    </div>
  )
}
